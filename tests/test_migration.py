import asyncio
import unittest
from types import SimpleNamespace
from unittest.mock import MagicMock, patch

from custom_components.brewcreator import async_migrate_entry
from custom_components.brewcreator.config_flow import BrewCreatorConfigFlow
from tests.factories import ha_device

FERMINATOR_ID = "4bed9c67-5578-4d23-babd-13de2cca6682"
TILT_ID = "9d0c5c1e-2f0a-4c55-9f4e-0f2d8c3b1a77"


def device(id: str, serial: str, manufacturer: str) -> SimpleNamespace:
    """A device as registered before 1.0.0, identified by serial number."""
    return ha_device(serial, id=id, name=id, manufacturer=manufacturer, serial_number=serial)


def entity(unique_id: str, config_entry_id: str = "entry") -> SimpleNamespace:
    return SimpleNamespace(unique_id=unique_id, config_entry_id=config_entry_id)


@patch("custom_components.brewcreator.er")
@patch("custom_components.brewcreator.dr")
class MigrationTestCase(unittest.TestCase):
    def migrate(self, dr, er, devices, entities_by_device, version=1):
        dr.async_entries_for_config_entry.return_value = devices
        er.async_entries_for_device.side_effect = (
            lambda registry, device_id, include_disabled_entities: entities_by_device.get(
                device_id, []
            )
        )
        hass = MagicMock()
        entry = SimpleNamespace(entry_id="entry", version=version)
        result = asyncio.run(async_migrate_entry(hass, entry))
        return result, hass, dr.async_get.return_value

    def test_identifiers_are_rewritten_to_equipment_ids(self, dr, er):
        result, hass, registry = self.migrate(
            dr,
            er,
            [
                device("dev-f", "0723-si7-4yk", "Brewolution"),
                device("dev-t", "oyc0gb", "Tilt"),
            ],
            {
                "dev-f": [
                    # The climate entity has an empty suffix
                    entity(f"brewcreator_{FERMINATOR_ID}_"),
                    entity(f"brewcreator_{FERMINATOR_ID}_original_gravity"),
                ],
                "dev-t": [
                    entity(f"brewcreator_{TILT_ID}_sg"),
                    entity(f"brewcreator_{TILT_ID}_last_activity"),
                ],
            },
        )

        self.assertTrue(result)
        registry.async_update_device.assert_any_call(
            "dev-f", new_identifiers={("brewcreator", FERMINATOR_ID)}
        )
        # A Tilt's serial is generated by BrewCreator, so it is cleared
        registry.async_update_device.assert_any_call(
            "dev-t", new_identifiers={("brewcreator", TILT_ID)}, serial_number=None
        )
        self.assertEqual(2, registry.async_update_device.call_count)
        hass.config_entries.async_update_entry.assert_called_once()
        self.assertEqual(
            {"version": 2}, hass.config_entries.async_update_entry.call_args.kwargs
        )

    def test_device_without_entities_keeps_its_identifiers(self, dr, er):
        result, hass, registry = self.migrate(
            dr, er, [device("dev-f", "0723-si7-4yk", "Brewolution")], {}
        )
        self.assertTrue(result)
        registry.async_update_device.assert_not_called()
        hass.config_entries.async_update_entry.assert_called_once()

    def test_entities_of_other_entries_and_foreign_unique_ids_are_ignored(self, dr, er):
        _, _, registry = self.migrate(
            dr,
            er,
            [device("dev-f", "0723-si7-4yk", "Brewolution")],
            {
                "dev-f": [
                    entity(f"brewcreator_{FERMINATOR_ID}_batch"),
                    entity("brewcreator_other-id_batch", config_entry_id="other"),
                    entity("something_else"),
                ]
            },
        )
        registry.async_update_device.assert_called_once_with(
            "dev-f", new_identifiers={("brewcreator", FERMINATOR_ID)}
        )

    def test_current_version_is_not_migrated(self, dr, er):
        result, hass, registry = self.migrate(dr, er, [], {}, version=2)
        self.assertTrue(result)
        hass.config_entries.async_update_entry.assert_not_called()

    def test_future_version_is_refused(self, dr, er):
        result, _, _ = self.migrate(dr, er, [], {}, version=3)
        self.assertFalse(result)

    def test_config_flow_version(self, dr, er):
        self.assertEqual(2, BrewCreatorConfigFlow.VERSION)


if __name__ == "__main__":
    unittest.main()
