"""Device registry info for BrewCreator equipment.

Devices are identified by BrewCreator's equipment ID. A Ferminator or Graviator keeps its hardware serial number when
it is registered again in BrewCreator, but probably gets a new equipment ID, so it gets a new device instead of sharing
one with its stale entities. A Tilt's iotHubBrewEquipmentId is generated by BrewCreator, so it isn't shown as a serial.
"""

from homeassistant.helpers.device_registry import BaseDeviceEntry, DeviceEntry, DeviceInfo, DeviceRegistry

from .api import BrewCreatorEquipment, Ferminator, Tilt
from .const import DOMAIN

TILT_MANUFACTURER = "Tilt"


def device_info(equipment: BrewCreatorEquipment) -> DeviceInfo:
    """Return device info for a Ferminator or hydrometer (Tilt, Graviator)."""
    if isinstance(equipment, Tilt):
        return DeviceInfo(
            identifiers={(DOMAIN, equipment.id)},
            manufacturer=TILT_MANUFACTURER,
            model=equipment.color.name,
            name=equipment.name,
        )
    info = DeviceInfo(
        identifiers={(DOMAIN, equipment.id)},
        manufacturer="Brewolution",
        serial_number=equipment.serial_number,
        model=equipment.raw_type,
        name=equipment.name,
    )
    if isinstance(equipment, Ferminator):
        info["sw_version"] = equipment.sw_version
        info["hw_version"] = equipment.hw_version
    return info


def find_device(registry: DeviceRegistry, equipment_id: str, config_entry_id: str) -> DeviceEntry | None:
    """Return the config entry's device of the equipment, if registered.

    HA 2026.11 deprecated async_get_device, as identifiers are only unique within a config entry since 2026.8.
    Older versions don't have async_get_device_by_identifier.
    """
    identifier = (DOMAIN, equipment_id)
    if hasattr(registry, "async_get_device_by_identifier"):
        return registry.async_get_device_by_identifier(identifier, config_entry_id)
    return registry.async_get_device(identifiers={identifier})


def equipment_ids(device: BaseDeviceEntry) -> set[str]:
    """Return the equipment IDs identifying a device of this integration."""
    return {identifier for domain, identifier in device.identifiers if domain == DOMAIN}


def device_name(device: BaseDeviceEntry) -> str | None:
    """Return the device's name as shown to the user."""
    return device.name_by_user or device.name
